#!/usr/bin/env python3
"""The implementation conditions each run set was collected under.

sec:metrics asks for delivery, age of information, realized sampling
intervals, computation time and saturation frequency "so that performance
differences can be interpreted in relation to implementation conditions".
On this platform those are MEASURED, not injected: no S_1 or S_2 impairment
model is applied anywhere, so what the table reports is what the hardware
did.

    python3 tools/dg5_platform.py --out results/tables
"""
from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from vertex.analysis.load import load_run                       # noqa: E402

#: Bare names. What the two assignments consist of is established in the
#: text; spelling it out again in every row made the environment column four
#: times wider than the numbers it labels, for no reader who did not already
#: know it.
HETEROGENEOUS = "heterogeneous"
HOMOGENEOUS = "homogeneous"

#: (run-set directory, environment, uncertainty profile), grouped by
#: environment.
#:
#: Environment and profile are two columns because they are two independent
#: facts about a run set, and collapsing them into one label made the table
#: say neither consistently: the persistent rows named the composition and
#: never the profile, the replication rows named the profile and dropped the
#: composition, and the word "persistent" appeared nowhere at all. Four rows
#: that are a 2x2 should look like one.
SETS = [("per-mixed", HETEROGENEOUS, "persistent"),
        ("rep-mixed", HETEROGENEOUS, "replication"),
        ("per-bridge5", HOMOGENEOUS, "persistent"),
        ("rep-bridge5", HOMOGENEOUS, "replication")]


def one_set(tag: str) -> dict | None:
    dirs = sorted(glob.glob(str(ROOT / "runs" / tag / "*-t*")))
    if not dirs:
        return None
    rho, pcomp, aoi, rh, cpu, sat, spread, wd = ([] for _ in range(8))
    for p in dirs:
        d = Path(p)
        spread.append(float(json.loads((d / "run.json").read_text())
                            .get("trigger_spread_s", 0.0)) * 1e3)
        r = load_run(d)
        ids = sorted(r.nodes)
        data = {i: r.nodes[i].data for i in ids}
        L = min(len(data[i]["timestamp"]) for i in ids)
        t = np.asarray(data[ids[0]]["timestamp"], float)[:L]
        h = float(np.median(np.diff(t)))
        span = max(1, int(round(0.125 / h)))
        for i in ids:
            col = lambda k: np.asarray(data[i][k], float)[:L]
            fresh = []
            for j in r.nodes[i].neighbours:
                f = col(f"rx_{j}") > 0
                w = f[:L // span * span].reshape(-1, span).any(1)
                rho.append(float(w.mean()))
                idx = np.arange(L)
                last = np.maximum.accumulate(np.where(f, idx, -1))
                ok = last >= 0
                aoi.append(float(np.mean((idx[ok] - last[ok]) * h)) * 1e3)
                fresh.append(w)
            if fresh:
                pcomp.append(float(np.all(np.vstack(fresh), axis=0).mean()))
            if "realized_h" in data[i]:
                rh.append(float(np.percentile(col("realized_h"), 99)) * 1e3)
            if "cpu_us" in data[i]:
                cpu.append(float(np.median(col("cpu_us"))))
            if "saturated" in data[i]:
                sat.append(100 * float(np.mean(col("saturated"))))
            if "watchdog" in data[i]:
                wd.append(int(np.max(col("watchdog")) > 0))
    f = lambda v: (float(np.median(v)) if v else np.nan)
    return dict(n=len(dirs), rho=f(rho), pcomp=f(pcomp), aoi=f(aoi),
                rh=f(rh), cpu=f(cpu), sat=f(sat),
                spread=f(spread), wd=int(sum(wd)))


def cell(v, fmt):
    return "--" if not np.isfinite(v) else fmt.format(v)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=None)
    a = ap.parse_args()
    rows = [(tag, env, prof, one_set(tag)) for tag, env, prof in SETS]
    rows = [(t, e, p, r) for t, e, p, r in rows if r]
    if not rows:
        print("no run sets under runs/", file=sys.stderr)
        return 2

    # Only the two delivery quantities. The rest -- AoI, realized period,
    # computation time, saturation -- belong with the control metrics and
    # were duplicating them here.
    # No trial count: it is a property of the campaign, stated once in the
    # text, and it is not a measured condition like the two that follow.
    hdr = ("environment", "profile", r"$\rho$", r"$P_{\mathrm{complete}}$")
    L = [r"% generated by tools/dg5_platform.py -- do not edit",
         r"\begin{tabular}{ll" + "r" * (len(hdr) - 2) + "}", r"\toprule",
         " & ".join(hdr) + r" \\", r"\midrule"]
    seen = None
    for tag, env, prof, r in rows:
        # The environment is written once per group: repeating it on the
        # second row of a pair invites the reader to look for a difference
        # between two identical strings.
        if seen is not None and env != seen:
            L.append(r"\addlinespace")
        L.append(" & ".join([
            env if env != seen else "", prof,
            cell(r["rho"], "{:.3f}"), cell(r["pcomp"], "{:.3f}")]) + r" \\")
        seen = env
    L += [r"\bottomrule", r"\end{tabular}"]
    text = "\n".join(L) + "\n"

    print(f"  {'run set':<16}{'profile':<13}{'n':>4}{'rho':>8}{'P_comp':>9}"
          f"{'AoI':>8}{'h p99':>8}{'CPU':>7}{'sat%':>8}{'spread':>9}{'w/d':>5}")
    for tag, env, prof, r in rows:
        print(f"  {tag:<16}{prof:<13}{r['n']:>4}{r['rho']:>8.3f}{r['pcomp']:>9.3f}"
              f"{r['aoi']:>8.1f}{cell(r['rh'],'{:.2f}'):>8}"
              f"{cell(r['cpu'],'{:.0f}'):>7}{cell(r['sat'],'{:.3f}'):>8}"
              f"{r['spread']:>9.1f}{r['wd']:>5}")
    if a.out:
        a.out.mkdir(parents=True, exist_ok=True)
        (a.out / "platform_conditions.tex").write_text(text)
        print(f"\n  wrote {a.out / 'platform_conditions.tex'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
