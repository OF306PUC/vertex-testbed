#!/usr/bin/env python3
"""The benchmark's parameter space, emitted from the manifests that run it.

Generated rather than written, for the reason the tables are: a parameter
transcribed by hand is a parameter that can disagree with the experiment it
claims to describe, and this one already did. Six values in the hand-written
version were wrong -- two initial-condition formulas, an adaptation gain
read off the wire instead of the manifest, a regularisation width quoted as
a constant when it is derived, an observer gain that is a state rather than
a parameter, and a graph quantity that named no object.

    python3 tools/dg5_params.py                      # to stdout
    python3 tools/dg5_params.py --out results        # results/dg5_parameters.tex

Reads `experiments/dg5-bridge5.yaml` and its `-rep` twin: everything but the
uncertainty profile and the dead-zone thresholds is shared, and those two are
reported side by side because they are the dimension the four run sets span.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

#: The horizon is a run argument (`--duration`), not a manifest field, so it
#: is the one number here that the manifests cannot supply.
T_END = 120.0


def load(name: str) -> dict:
    """The manifest as written, plus the neighbour lists `structure` implies.

    A manifest declares either a generator or explicit edges, never both, so
    the graph has to be expanded before its spectrum can be taken.
    """
    from vertex.topology.loader import load_manifest
    raw = yaml.safe_load((ROOT / "experiments" / f"{name}.yaml").read_text())
    m = load_manifest(raw)
    by = {n.id: list(n.neighbors) for n in m.nodes}
    for n in raw["nodes"]:
        n["neighbors"] = by[n["id"]]
    # The microgrid block comes from the RESOLVED spec, not the YAML: a
    # manifest omits every field it leaves at its default -- beta_c, kappa_o,
    # xi, c_0 among them -- and a parameter table built from the file alone
    # would simply not mention the ones that matter most.
    raw["controller"]["microgrid"] = m.controller.microgrid.model_dump()
    return raw


def graph_spectrum(nodes) -> dict:
    """The three quantities, named, because they answer different questions.

    `lambda_2` describes the topology. `lambda_min(L+B)` is the rate of the
    pinned problem in continuous time. `rho(D^-1 A)` is the contraction per
    PACKET, and it is the one that bounds h_v -- the layer performs one
    Jacobi sweep per exchange, not per tick, because neighbour values are
    held in between.
    """
    ids = sorted(n["id"] for n in nodes)
    idx = {i: k for k, i in enumerate(ids)}
    N = len(ids)
    A = np.zeros((N, N))
    for n in nodes:
        for j in n["neighbors"]:
            A[idx[n["id"]], idx[j]] = 1.0
    return A, np.array([0.0] * N)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument("--base", default="dg5-bridge5")
    a = ap.parse_args()

    per, rep = load(a.base), load(f"{a.base}-rep")
    mg, mgr = per["controller"]["microgrid"], rep["controller"]["microgrid"]
    h = float(per["controller"]["dt_s"])
    h_v = float(per["nodes"][0]["publish_period_s"])
    ref = per["coordination"]["reference"]
    pin = per["coordination"]["pinned"]
    nodes = sorted(per["nodes"], key=lambda n: n["id"])

    A, _ = graph_spectrum(nodes)
    b = np.array([float(pin.get(n["id"], 0.0)) for n in nodes])
    L = np.diag(A.sum(1)) - A
    lam2 = float(np.sort(np.linalg.eigvalsh(L))[1])
    lmin = float(np.sort(np.linalg.eigvalsh(L + np.diag(b)))[0])
    rhoJ = float(max(abs(np.linalg.eigvals(
        np.diag(1.0 / (A.sum(1) + b)) @ A))))

    kap = [float(n["plant"]["kappa"]) for n in nodes]
    X0 = [n["plant"]["X0"] for n in nodes]
    z0 = [n["plant"]["z0"] for n in nodes]
    S = [n["plant"]["S"] for n in nodes]
    eps_p = [float(mg["eps"][n["id"]]) for n in nodes]
    eps_r = [float(mgr["eps"][n["id"]]) for n in nodes]
    delta_x = 0.01 * sum(abs(v) for v in ref)
    delta_c = 2 * h
    Gam = [k * k * float(mg["Phi"]) for k in kap]

    V = lambda v: r"\begin{bmatrix}" + " & ".join(f"{x:g}" for x in v) + r"\end{bmatrix}^{\mathsf T}"
    SET = lambda v, f="{:.4f}": r"\{" + ",\\, ".join(f.format(x) for x in v) + r"\}"

    L_ = [
        r"% generated by tools/dg5_params.py -- do not edit",
        r"\begin{enumerate}",
        r"\item \textbf{Rates and horizon:}",
        r"\begin{align*}",
        rf"  h &= {h*1e3:g}\ \mathrm{{ms}}, \qquad h_v = {h_v*1e3:g}\ "
        rf"\mathrm{{ms}} = {h_v/h:g}h, \qquad T_{{\mathrm{{end}}}} = {T_END:g}\ \mathrm{{s}}",
        r"\end{align*}",
        "",
        r"\item \textbf{Plant:}",
        r"\begin{align*}",
        r"  \kappa_i &= \tfrac{i}{15},\quad i\in\{1,\dots,5\},"
        rf"\qquad \textstyle\sum_i\kappa_i = {sum(kap):g} \\",
        rf"  X^\ast &= X_\Sigma^d = \begin{{bmatrix}}{ref[0]:g}\ \mathrm{{kW}} & "
        rf"{ref[1]:g}\ \mathrm{{kVAr}}\end{{bmatrix}}^{{\mathsf T}} \\",
        r"  B_i &= 108I_{2\times2}, \qquad "
        r"S_i = \begin{bmatrix}i & i\end{bmatrix}^{\mathsf T} \\",
        r"  X_i[0] &\in \{" + ",\\, ".join(V(v) for v in X0) + r"\} \\",
        rf"  P_{{\max}} &= {mg['p_max']:g}\ \mathrm{{kW}}, \qquad "
        rf"Q_{{\max}} = {mg['q_max']:g}\ \mathrm{{kVAr}} \\",
        r"  a_\zeta^{\mathrm{rep}}(t) &= 10^{-3}e^{-5t}, \qquad "
        r"a_\zeta^{\mathrm{per}}(t) = 10^{-3}(0.75+0.25\sin 0.1t)",
        r"\end{align*}",
        "",
        rf"\item \textbf{{Graph:}} undirected {len(nodes)}-ring, "
        rf"pinned at DG {min(pin)} ($b = e_{min(pin)}$)",
        r"\begin{align*}",
        rf"  \lambda_2(\mathcal L) &= {lam2:.4f}, \qquad "
        rf"\lambda_{{\min}}(\mathcal L + B) = {lmin:.4f} \\",
        rf"  \rho(D^{{-1}}A) &= {rhoJ:.4f}, \qquad "
        r"D = \operatorname{diag}(d_i + b_i), \quad A \text{ the adjacency matrix}",
        r"\end{align*}",
        "",
        r"\item \textbf{Virtual layer:}",
        r"\begin{align*}",
        rf"  \alpha_0 &= {mg['alpha_0']:g}, \qquad \kappa_o = {mg.get('kappa_o', 1e-3):g},"
        rf" \qquad \xi_i = {mg.get('xi', 0.025):g} \\",
        rf"  \delta_o &= h_v = {h_v*1e3:g}\ \mathrm{{ms}}, \qquad "
        rf"\alpha_{{\max}} = \alpha_0T_o/\delta_o = {mg['alpha_0']*mg['T_o']/h_v:g} \\",
        rf"  c_i[0] &= {mg.get('c_0', 0.1):g}, \qquad z_i[0] \in \{{"
        + ",\\, ".join(V(v) for v in z0) + r"\}",
        r"\end{align*}",
        "",
        r"\item \textbf{$\mathcal C_{\mathrm{LC0}}$, $\mathcal C_{\mathrm{LC+}}$:}",
        r"\begin{align*}",
        rf"  T_o &= {mg['T_o']:g}\ \mathrm{{s}}, \qquad T_c = {mg['T_c']:g}\ \mathrm{{s}} \\",
        rf"  \beta_c &= {mg['beta_c']:g}, \qquad \delta_c = 2h = {delta_c*1e3:g}\ "
        rf"\mathrm{{ms}} \;\Rightarrow\; h\beta_c/\delta_c = {h*mg['beta_c']/delta_c:g},"
        rf"\quad \lambda_{{c,h}}^{{\max}} = {mg['beta_c']/delta_c:g}\ \mathrm{{s}}^{{-1}} \\",
        rf"  \Phi_i &= {mg['Phi']:g} \text{{ (scalar)}}, \qquad \Gamma_i = \kappa_i^2\Phi_i "
        + SET(Gam, "{:.5f}") + r", \qquad \widehat S_i[0] = 0_2",
        r"\end{align*}",
        "",
        r"\item \textbf{$\mathcal C_{\mathrm{AA}}$, $\mathcal C_{\mathrm{DZ}}$:}",
        r"\begin{align*}",
        rf"  \vartheta_i[0] &= {mg.get('vartheta0', 0.0):g}, \qquad "
        rf"\mu_{{\max}} = {mg['mu_max']:g}, \qquad \gamma_i = {mg['gamma']:g}, "
        rf"\qquad \delta_\varepsilon = 0.25 \\",
        r"  \varepsilon_i^{\mathrm{per}} &= " + SET(eps_p) + r" \\",
        r"  \varepsilon_i^{\mathrm{rep}} &= " + SET(eps_r),
        r"\end{align*}",
        "",
        r"\item \textbf{Evaluation band:}",
        r"\begin{align*}",
        rf"  \delta_x &= 0.01\|X^\ast\|_1 = {delta_x:g}, \qquad "
        rf"\text{{gate }} E_z \le \delta_x/4 = {delta_x/4:g}",
        r"\end{align*}",
        r"\end{enumerate}",
    ]
    text = "\n".join(L_) + "\n"
    if a.out:
        a.out.mkdir(parents=True, exist_ok=True)
        (a.out / "dg5_parameters.tex").write_text(text)
        print(f"  wrote {a.out / 'dg5_parameters.tex'}")
        print(f"  alpha_0 = {mg['alpha_0']:g} is a DECLARED value: the source "
              f"relation alpha_0 = 1/(a_o T_o) with a_o = 1/3 gives 0.1.")
        print(f"  a_o is NOT listed: a_o[k] = c_i[k] f_o[k] is a state, and c_i adapts.")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
